  it('applies the 30-day and maximum-100 run retention policy inside restore', async () => {
    const module = await loadDatabase()
    module.setCustomDbPath(path.join(makeTempRoot(), 'minddiary.db'))
    module.initialize()
    const database = module.getDb()
    databases.push(database)
    const now = Date.now()
    const recentRuns = Array.from({ length: 101 }, (_, index) => {
      const timestamp = new Date(now - index * 60_000).toISOString()
      return {
        ...planningRun,
        id: `00000000-0000-4000-8000-${String(index + 1).padStart(12, '0')}`,
        created_at: timestamp,
        updated_at: timestamp,
        closed_at: null,
        close_reason: null,
      }
    })
    const oldTimestamp = new Date(now - 31 * 24 * 60 * 60 * 1000).toISOString()
    const oldRun = {
      ...planningRun,
      id: 'ffffffff-ffff-4fff-bfff-ffffffffffff',
      created_at: oldTimestamp,
      updated_at: oldTimestamp,
      closed_at: null,
      close_reason: null,
    }
    const oldCandidate = {
      ...planningCandidate,
      planning_run_id: oldRun.id,
      user_disposition: 'unselected',
      operation_id: null,
      outcome_kind: null,
      outcome_observed_at: null,
      admitted_at: oldTimestamp,
      updated_at: oldTimestamp,
    }

    module.restoreBackupData({
      planning_runs: [...recentRuns, oldRun],
      planning_run_candidates: [oldCandidate],
    }, 7)

    const rows = database.prepare('SELECT id FROM planning_runs ORDER BY created_at DESC, id DESC').all() as Array<{ id: string }>
    expect(rows).toHaveLength(100)
    expect(rows[0]?.id).toBe(recentRuns[0]?.id)
    expect(rows.some(row => row.id === recentRuns[100]?.id)).toBe(false)
    expect(rows.some(row => row.id === oldRun.id)).toBe(false)
    expect(database.prepare('SELECT COUNT(*) AS count FROM planning_run_candidates').get()).toEqual({ count: 0 })
  })

