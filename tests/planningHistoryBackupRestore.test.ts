  it('rolls back all imported tables when a real SQLite foreign-key failure occurs', async () => {
    const module = await loadDatabase()
    module.setCustomDbPath(path.join(makeTempRoot(), 'minddiary.db'))
    module.initialize()
    const database = module.getDb()
    databases.push(database)
    database.prepare(`
      INSERT INTO planning_runs (
        id, contract_version, entry_point, planning_date, target_date,
        generation_result_kind, context_summary_json, created_at, updated_at,
        closed_at, close_reason
      ) VALUES (
        @id, @contract_version, @entry_point, @planning_date, @target_date,
        @generation_result_kind, @context_summary_json, @created_at, @updated_at,
        @closed_at, @close_reason
      )
    `).run(planningRun)
    database.prepare(`
      INSERT INTO study_tasks (id, title, planned_date, status, source)
      VALUES (1, 'preserved task', '2026-08-13', 'todo', 'ai')
    `).run()

    expect(() => module.restoreBackupData({
      planning_runs: [],
      planning_run_candidates: [],
      study_task_action_receipts: [{
        operation_id: '323e4567-e89b-42d3-a456-426614174000',
        operation_kind: 'today_action',
        action_contract_version: 'confirmed-study-task-action.v1',
        request_digest: 'a'.repeat(64),
        expected_current_date: '2026-08-13',
        planned_date: '2026-08-13',
        task_id: 999,
        created_at: '2026-08-13T01:00:00.000Z',
      }],
    }, 7)).toThrow(/foreign key/i)

    expect(database.prepare('SELECT id FROM planning_runs').all()).toEqual([{ id: planningRun.id }])
    expect(database.prepare('SELECT id, title FROM study_tasks').all()).toEqual([{ id: 1, title: 'preserved task' }])
    expect(database.prepare('PRAGMA foreign_key_check').all()).toEqual([])
    expect(database.prepare('PRAGMA integrity_check').get()).toEqual({ integrity_check: 'ok' })
  })

  it('rolls back an otherwise valid import when the real SQLite integrity check is not ok', async () => {
    const module = await loadDatabase()
    module.setCustomDbPath(path.join(makeTempRoot(), 'minddiary.db'))
    module.initialize()
    const database = module.getDb()
    databases.push(database)
    database.prepare(`
      INSERT INTO planning_runs (
        id, contract_version, entry_point, planning_date, target_date,
        generation_result_kind, context_summary_json, created_at, updated_at,
        closed_at, close_reason
      ) VALUES (
        @id, @contract_version, @entry_point, @planning_date, @target_date,
        @generation_result_kind, @context_summary_json, @created_at, @updated_at,
        @closed_at, @close_reason
      )
    `).run(planningRun)
    database.exec(`
      CREATE TABLE integrity_sentinel (value INTEGER CHECK (value = 1));
      PRAGMA ignore_check_constraints = ON;
      INSERT INTO integrity_sentinel (value) VALUES (2);
      PRAGMA ignore_check_constraints = OFF;
    `)
    expect(database.prepare('PRAGMA integrity_check').all()).not.toEqual([{ integrity_check: 'ok' }])

    expect(() => module.restoreBackupData({
      planning_runs: [],
      planning_run_candidates: [],
    }, 7)).toThrow(/integrity_check/i)

    expect(database.prepare('SELECT id FROM planning_runs').all()).toEqual([{ id: planningRun.id }])
  })

