vi.mock('../electron/logger', () => ({
  logger: {
    debug: vi.fn(),
    info: vi.fn(),
    log: vi.fn(),
    warn: vi.fn(),
    error: vi.fn(),
  },
}))

type DatabaseModule = {
  initialize: () => void
  setCustomDbPath: (filepath: string) => void
  getDb: () => Database.Database
  exportBackupData: () => Record<string, unknown>
  restoreBackupData: (data: Record<string, unknown>, manifestSchemaVersion?: number) => void
}

const databases: Database.Database[] = []
const tempRoots: string[] = []

function makeTempRoot(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'minddiary-planning-restore-'))
  tempRoots.push(root)
  return root
}

async function loadDatabase(): Promise<DatabaseModule> {
  vi.resetModules()
  vi.doMock('electron', () => ({
    app: {
      getPath: vi.fn(() => makeTempRoot()),
      isPackaged: false,
    },
    safeStorage: {
      isEncryptionAvailable: vi.fn(() => false),
      encryptString: vi.fn((value: string) => Buffer.from(value)),
      decryptString: vi.fn((value: Buffer) => value.toString('utf8')),
    },
  }))
  vi.doMock('../electron/mistakeImageStorage', () => ({
    deleteManagedMistakeImage: vi.fn(async () => undefined),
    getMistakeImageReferenceKey: vi.fn(() => null),
  }))
  const imported = await import('../electron/database') as unknown as DatabaseModule | { default: DatabaseModule }
  return 'default' in imported ? imported.default : imported
}

